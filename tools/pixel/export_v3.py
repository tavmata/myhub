"""Export the pixel room and marks for hub v3 (assets/v3)."""
import json, os, random, sys
from PIL import Image
from px import PAL
import scene2
from marks import tv32, tv16

DST = sys.argv[1]
IMG = os.path.join(DST, "img")
os.makedirs(IMG, exist_ok=True)

base = scene2.scene(dice=False, corners=False)
full = scene2.scene(dice=True, corners=False)
rows = base.to_rows()
used = sorted({ch for r in full.to_rows() for ch in r if ch != "."} | set("wUYsSRK1234jx"))
pal = {k: PAL[k] for k in used}

FACES = {
    1: [".....", ".....", "..o..", ".....", "....."],
    2: [".o...", ".....", ".....", ".....", "...o."],
    3: [".o...", ".....", "..o..", ".....", "...o."],
    4: [".o.o.", ".....", ".....", ".....", ".o.o."],
    5: [".o.o.", ".....", "..o..", ".....", ".o.o."],
    6: [".o.o.", ".....", ".o.o.", ".....", ".o.o."],
}
def die(face, border, fill, pip):
    out = [border * 7]
    for r in FACES[face]:
        out.append(border + "".join(pip if c == "o" else fill for c in r) + border)
    out.append(border * 7)
    return out
dice = {
    "red": {f: die(f, "U", "R", "w") for f in FACES},
    "yel": {f: die(f, "Y", "s", "S") for f in FACES},
}
PINHAO = [".4.", "334", "233", "223", ".1."]

js = "// Generated by export_v3.py from the 72x72 pixel room. One character per pixel; '.' is transparent.\n"
js += "export const PAL = " + json.dumps(pal) + ";\n"
js += "export const ROOM = " + json.dumps(rows, indent=0) + ";\n"
js += "export const DICE = " + json.dumps(dice) + ";\n"
js += "export const PINHAO = " + json.dumps(PINHAO) + ";\n"
js += """export const SPOTS = {
  screen: { x: 27, y: 18, w: 13, h: 12 },
  knobs: [{ x: 42, y: 18, w: 3, h: 3 }, { x: 42, y: 22, w: 3, h: 3 }],
  dieRed: { x: 38, y: 57 }, dieYel: { x: 46, y: 60 },
  capyEye: [[22, 55], [23, 55]], qqEye: [[53, 33], [54, 33]],
  stars: [[6, 7], [10, 9], [4, 11], [18, 11]],
  pinhao: { x: 66, y: 52 },
  capy: { x: 1, y: 50, w: 30, h: 19 }, qq: { x: 49, y: 27, w: 19, h: 33 }, cuia: { x: 59, y: 61, w: 6, h: 6 },
};
"""
open(os.path.join(DST, "pixel-room.js"), "w", encoding="utf-8").write(js)

full.save_png(os.path.join(IMG, "room.png"), 1)
for name, cv in (("tv32", tv32()), ("tv16", tv16())):
    open(os.path.join(IMG, f"{name}.svg"), "w", encoding="utf-8").write(cv.svg())
tv16().save_png(os.path.join(IMG, "favicon-16.png"), 1)
tv32().save_png(os.path.join(IMG, "favicon-32.png"), 1)
# apple touch icon: the 32px mark at 5x on the night wall
t = Image.new("RGBA", (32 * 5, 32 * 5), (0, 0, 0, 0))
tv32().save_png(os.path.join(IMG, "_t.png"), 5)
mark = Image.open(os.path.join(IMG, "_t.png"))
icon = Image.new("RGBA", (180, 180), (10, 23, 28, 255))
icon.alpha_composite(mark, (10, 8))
icon.save(os.path.join(IMG, "apple-touch-icon.png"))
os.remove(os.path.join(IMG, "_t.png"))
# TV static: grey noise, scaled up with pixelated rendering in CSS
rnd = random.Random(7)
n = Image.new("L", (96, 64))
n.putdata([rnd.choice((18, 40, 70, 110, 150, 200, 235)) for _ in range(96 * 64)])
n.save(os.path.join(IMG, "static.png"), optimize=True)
print("exported", len(rows), "rows,", len(pal), "colours")
